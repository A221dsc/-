"""Approximate offline reference for the full 256-region problem.

Beam search over windows. A state is the per-region mode vector plus the last
switch window and the rebuild budget used in the current window. Candidates are
generated by keeping all modes or greedily switching the highest-benefit legal
regions (up to the rebuild and entity budgets); the cost of each candidate uses
the calibrated cost model on the actual per-region loads. This is an
approximate reference, not a proven optimum.
"""
import argparse
import json
from pathlib import Path

import numpy as np

SIDE = 16
REGIONS = SIDE * SIDE
MODES = 3
COOLDOWN = 2


def read_table(path):
    table = {}
    with Path(path).open(encoding="utf-8") as handle:
        next(handle)
        for line in handle:
            fields = line.split(",")
            table[(int(fields[0]), int(fields[1]))] = (
                float(fields[2]), float(fields[3]), float(fields[4]), float(fields[5]))
    windows = max(w for w, _ in table) + 1
    array = np.zeros((windows, REGIONS, 4))
    for (window, region), value in table.items():
        array[window, region] = value
    return array


def cost_matrix(model, loads):
    windows = loads.shape[0]
    out = np.zeros((windows, REGIONS, MODES))
    for w in range(windows):
        for r in range(REGIONS):
            q, n, u, c = loads[w, r]
            query = np.array([q, q * n, n * c, q * np.sqrt(max(n, 0.0)), c])
            update = np.array([u, u * np.sqrt(max(n, 0.0))])
            for m in range(MODES):
                out[w, r, m] = query @ np.array(model["query"][m]) + \
                               update @ np.array(model["update"][m])
    return out


def switch_costs(model, loads):
    names = ["SCAN", "FINE_GRID", "LOCAL_QUAD"]
    out = np.zeros((REGIONS, MODES, MODES))
    for r in range(REGIONS):
        entity = float(loads[:, r, 1].max())
        for s in range(MODES):
            for t in range(MODES):
                out[r, s, t] = float(np.array([1.0, entity]) @
                                     np.array(model["switch"][names[s]][names[t]]))
    return out


def beam_search(loads, cm, sw, budget_entities=6000.0, max_rebuilds=4, width=32):
    windows = cm.shape[0]
    beam = [(0.0, np.zeros(REGIONS, dtype=np.int8), np.full(REGIONS, -COOLDOWN, dtype=np.int64))]
    for w in range(windows):
        candidates = []
        for total, modes, last in beam:
            # candidate 0: keep everything
            base = total + cm[w, np.arange(REGIONS), modes].sum()
            candidates.append((base, modes.copy(), last.copy()))
            # benefits of switching to each mode
            ben = cm[w, :, modes].diagonal() if False else np.zeros((REGIONS, MODES))
            for r in range(REGIONS):
                for t in range(MODES):
                    if t == modes[r]:
                        ben[r, t] = -1e18
                    else:
                        ben[r, t] = cm[w, r, modes[r]] - cm[w, r, t] - sw[r, modes[r], t]
            # greedy: add switches in benefit order while legal and under budget
            order = np.dstack(np.unravel_index(np.argsort(ben, axis=None)[::-1], ben.shape))[0]
            chosen = modes.copy()
            chosen_last = last.copy()
            rebuilds = 0
            entities = 0.0
            added = 0
            running = base
            for region, target in order:
                if ben[region, target] <= 0:
                    break
                if chosen[region] != modes[region]:
                    continue
                if w - last[region] <= 1:
                    continue
                if target != 0:
                    if rebuilds >= max_rebuilds:
                        continue
                    if entities + loads[:, region, 1].max() > budget_entities:
                        continue
                chosen[region] = target
                chosen_last[region] = w
                if target != 0:
                    rebuilds += 1
                    entities += float(loads[:, region, 1].max())
                running += -ben[region, target] * 0 + (cm[w, region, target] +
                                                       sw[region, modes[region], target] -
                                                       cm[w, region, modes[region]])
                added += 1
                if added >= max_rebuilds:
                    candidates.append((running, chosen.copy(), chosen_last.copy()))
            if added == 0:
                continue
        candidates.sort(key=lambda item: item[0])
        beam = candidates[:width]
    return min(item[0] for item in beam)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("calibration", type=Path)
    parser.add_argument("scenarios", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--scenario", default="test-2-den011d")
    parser.add_argument("--width", type=int, default=32)
    args = parser.parse_args()
    model = json.loads((args.calibration / "cost_model.json").read_text(encoding="utf-8"))
    loads = read_table(args.scenarios / "loads" / f"{args.scenario}.actual_loads.csv")
    cm = cost_matrix(model, loads)
    sw = switch_costs(model, loads)
    value = beam_search(loads, cm, sw, width=args.width)
    idealized = float(sum(min(cm[w, r, m] for m in range(MODES))
                          for w in range(cm.shape[0]) for r in range(REGIONS)))
    args.output.mkdir(parents=True, exist_ok=True)
    import csv
    with (args.output / "beam_reference.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["instance", "method", "beam_width", "cost_ms"])
        writer.writerow([args.scenario, "beam search (approximate)", args.width, value / 1e6])
        writer.writerow([args.scenario, "idealized lower bound", 0, idealized / 1e6])
    print(f"beam width {args.width}: {value/1e6:.3f} ms")
    print(f"idealized lower bound: {idealized/1e6:.3f} ms")


if __name__ == "__main__":
    main()
